CREATE TABLE users (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email         text NOT NULL UNIQUE CHECK (email = lower(email)),
    name          text NOT NULL CHECK (length(name) BETWEEN 1 AND 60),
    password_hash text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE groups (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name        text NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    invite_code text NOT NULL UNIQUE,
    created_by  uuid NOT NULL REFERENCES users(id),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE group_members (
    group_id  uuid NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    user_id   uuid NOT NULL REFERENCES users(id),
    joined_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (group_id, user_id)
);
CREATE INDEX group_members_user_idx ON group_members (user_id);

-- The id is generated by the client, so retrying a create after a dropped
-- response cannot add the expense twice.
CREATE TABLE expenses (
    id           uuid PRIMARY KEY,
    group_id     uuid NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    paid_by      uuid NOT NULL REFERENCES users(id),
    description  text NOT NULL CHECK (length(description) BETWEEN 1 AND 120),
    amount_paise bigint NOT NULL CHECK (amount_paise > 0),
    split_type   text NOT NULL CHECK (split_type IN ('equal', 'exact', 'percent', 'shares')),
    created_by   uuid NOT NULL REFERENCES users(id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    deleted_at   timestamptz
);
CREATE INDEX expenses_group_idx ON expenses (group_id, created_at DESC);

CREATE TABLE expense_shares (
    expense_id  uuid NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
    user_id     uuid NOT NULL REFERENCES users(id),
    share_paise bigint NOT NULL CHECK (share_paise >= 0),
    PRIMARY KEY (expense_id, user_id)
);

-- Invariant enforced by the database, not just the API: an expense's shares
-- always add up to its amount. Checked at COMMIT so the expense and its shares
-- can be inserted in any order inside one transaction.
CREATE FUNCTION assert_expense_balanced() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    eid   uuid;
    amt   bigint;
    total bigint;
BEGIN
    IF TG_TABLE_NAME = 'expenses' THEN
        eid := NEW.id;
    ELSIF TG_OP = 'DELETE' THEN
        eid := OLD.expense_id;
    ELSE
        eid := NEW.expense_id;
    END IF;

    SELECT amount_paise INTO amt FROM expenses WHERE id = eid;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;
    SELECT COALESCE(sum(share_paise), 0) INTO total FROM expense_shares WHERE expense_id = eid;
    IF total <> amt THEN
        RAISE EXCEPTION 'expense % shares sum to % paise but amount is %', eid, total, amt
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER expenses_balanced
    AFTER INSERT OR UPDATE ON expenses
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION assert_expense_balanced();

CREATE CONSTRAINT TRIGGER expense_shares_balanced
    AFTER INSERT OR UPDATE OR DELETE ON expense_shares
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION assert_expense_balanced();

-- One row per Razorpay order. status only ever moves created -> paid | failed.
CREATE TABLE payments (
    id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    group_id            uuid NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    payer_id            uuid NOT NULL REFERENCES users(id),
    payee_id            uuid NOT NULL REFERENCES users(id),
    amount_paise        bigint NOT NULL CHECK (amount_paise >= 100),
    razorpay_order_id   text NOT NULL UNIQUE,
    razorpay_payment_id text UNIQUE,
    status              text NOT NULL DEFAULT 'created' CHECK (status IN ('created', 'paid', 'failed')),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CHECK (payer_id <> payee_id)
);

CREATE TABLE settlements (
    id           uuid PRIMARY KEY,
    group_id     uuid NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    from_user    uuid NOT NULL REFERENCES users(id),
    to_user      uuid NOT NULL REFERENCES users(id),
    amount_paise bigint NOT NULL CHECK (amount_paise > 0),
    method       text NOT NULL CHECK (method IN ('cash', 'razorpay')),
    -- UNIQUE: a captured payment can become a settlement exactly once, no matter
    -- how many webhooks or client callbacks report it.
    payment_id   uuid UNIQUE REFERENCES payments(id),
    created_by   uuid NOT NULL REFERENCES users(id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    CHECK (from_user <> to_user),
    CHECK ((method = 'razorpay') = (payment_id IS NOT NULL))
);
CREATE INDEX settlements_group_idx ON settlements (group_id);

-- Razorpay delivers webhooks at least once; the event id is the dedupe key.
CREATE TABLE webhook_events (
    event_id     text PRIMARY KEY,
    event_type   text NOT NULL,
    payload      jsonb NOT NULL,
    received_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE activity (
    id         bigserial PRIMARY KEY,
    group_id   uuid NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    actor_id   uuid REFERENCES users(id),
    kind       text NOT NULL,
    summary    text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX activity_group_idx ON activity (group_id, id DESC);
