import re
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, EmailStr, Field, field_validator

from .money import SplitType

MAX_AMOUNT = 10_00_000_00  # ₹10 lakh in paise
# Same rule as the users.upi_id CHECK constraint: handle@psp, e.g. asha.k@okaxis
UPI_ID = re.compile(r"^[A-Za-z0-9._-]{2,255}@[A-Za-z][A-Za-z0-9]{1,63}$")


class RegisterIn(BaseModel):
    email: EmailStr
    name: str = Field(min_length=1, max_length=60)
    password: str = Field(min_length=8, max_length=128)

    @field_validator("email")
    @classmethod
    def lower(cls, v: str) -> str:
        return v.lower()

    @field_validator("name")
    @classmethod
    def strip(cls, v: str) -> str:
        v = v.strip()
        if not v:
            raise ValueError("name cannot be blank")
        return v


class LoginIn(BaseModel):
    email: EmailStr
    password: str

    @field_validator("email")
    @classmethod
    def lower(cls, v: str) -> str:
        return v.lower()


class GroupIn(BaseModel):
    name: str = Field(min_length=1, max_length=80)


class SplitEntry(BaseModel):
    user_id: UUID
    value: int = 0


class ExpenseIn(BaseModel):
    id: UUID  # generated by the client: makes retries idempotent
    description: str = Field(min_length=1, max_length=120)
    amount_paise: int = Field(gt=0, le=MAX_AMOUNT)
    paid_by: UUID
    split_type: SplitType
    splits: list[SplitEntry] = Field(min_length=1, max_length=50)


class SettlementIn(BaseModel):
    id: UUID  # client generated, same idempotency trick as expenses
    from_user: UUID
    to_user: UUID
    amount_paise: int = Field(gt=0, le=MAX_AMOUNT)
    method: Literal["cash", "upi"] = "cash"


class ProfileIn(BaseModel):
    upi_id: str | None

    @field_validator("upi_id")
    @classmethod
    def valid_upi(cls, v: str | None) -> str | None:
        v = (v or "").strip()
        if not v:
            return None
        if not UPI_ID.match(v):
            raise ValueError("Enter a UPI ID like name@okaxis")
        return v


class PaymentOrderIn(BaseModel):
    to_user: UUID
    amount_paise: int = Field(ge=100, le=MAX_AMOUNT)  # Razorpay minimum is ₹1


class PaymentVerifyIn(BaseModel):
    razorpay_order_id: str
    razorpay_payment_id: str
    razorpay_signature: str
